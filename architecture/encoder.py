import math
from functools import partial
import numpy as np

import torch  
import torch.nn as nn 

def drop_path(x, drop_prob: float = 0., training: bool = False):
    if drop_prob == 0. or not training:
        return x
    keep_prob = 1 - drop_prob
    shape = (x.shape[0],) + (1,) * (x.ndim - 1)  # work with diff dim tensors, not just 2D ConvNets
    random_tensor = keep_prob + torch.rand(shape, dtype=x.dtype, device=x.device)
    random_tensor.floor_()  # binarize
    output = x.div(keep_prob) * random_tensor
    return output

def _no_grad_trunc_normal_(tensor, mean, std, a, b):
    # Cut & paste from PyTorch official master until it's in a few official releases - RW
    # Method based on https://people.sc.fsu.edu/~jburkardt/presentations/truncated_normal.pdf
    def norm_cdf(x):
        # Computes standard normal cumulative distribution function
        return (1. + math.erf(x / math.sqrt(2.))) / 2.

    with torch.no_grad():
        # Values are generated by using a truncated uniform distribution and
        # then using the inverse CDF for the normal distribution.
        # Get upper and lower cdf values
        l = norm_cdf((a - mean) / std)
        u = norm_cdf((b - mean) / std)

        # Uniformly fill tensor with values from [l, u], then translate to
        # [2l-1, 2u-1].
        tensor.uniform_(2 * l - 1, 2 * u - 1)

        # Use inverse cdf transform for normal distribution to get truncated
        # standard normal
        tensor.erfinv_()

        # Transform to proper mean, std
        tensor.mul_(std * math.sqrt(2.))
        tensor.add_(mean)

        # Clamp to ensure it's in the proper range
        tensor.clamp_(min=a, max=b)
        return tensor
    
def trunc_normal_(tensor, mean=0., std=1., a=-2., b=2.):
    # type: (nn.Tensor, float, float, float, float) -> nn.Tensor
    return _no_grad_trunc_normal_(tensor, mean, std, a, b)


def apply_masks(x, masks):
    """
    :param x: tensor of shape [B (batch-size), N (num-patches), D (feature-dim)]
    :param masks: list of tensors containing indices of patches in [N] to keep
    """
    all_x = []
    for m in masks:
        mask_keep = m.unsqueeze(-1).repeat(1, 1, x.size(-1))
        all_x += [torch.gather(x, dim=1, index=mask_keep)]
    return torch.cat(all_x, dim=0)


def repeat_interleave_batch(x, B, repeat):
    N = len(x) // B
    x = torch.cat([
        torch.cat([x[i*B:(i+1)*B] for _ in range(repeat)], dim=0)
        for i in range(N)
    ], dim=0)
    return x

class DropPath(nn.Module):
    """Drop paths (Stochastic Depth) per sample  (when applied in main path of residual blocks).
    """
    def __init__(self, drop_prob=None):
        super(DropPath, self).__init__()
        self.drop_prob = drop_prob

    def forward(self, x):
        return drop_path(x, self.drop_prob, self.training)


"""Simple neural network with one hidden layer and GELU activation
    input -> Linear -> GELU -> Dropout -> Linear -> Dropout -> output
parameters:
    in_features (int): Number of input features
    hidden_features (int, optional): Number of hidden features. Defaults to None.
    out_features (int, optional): Number of output features. Defaults to None.
    act_layer (nn.Module, optional): Activation layer. Defaults to nn.GELU.
    drop (float, optional): Dropout rate. Defaults to 0.
"""
class MLP(nn.Module):

    def __init__(self, in_features, hidden_features=None, out_features=None, act_layer=nn.GELU, drop=0.):
        super().__init__()
        out_features = out_features or in_features
        hidden_features = hidden_features or in_features
        self.fc1 = nn.Linear(in_features, hidden_features)
        self.act = act_layer()
        self.fc2 = nn.Linear(hidden_features, out_features)
        self.drop = nn.Dropout(drop)

    def forward(self, x):
        x = self.fc1(x)
        x = self.act(x)
        x = self.drop(x)
        x = self.fc2(x)
        x = self.drop(x)
        return x
    
"""Attention mechanism with multi-head attention with non varying input and output dimensions. 
It computes the attention scores and applies them to the value vectors to produce the output.


parameters:
    dim (int): Number of input and output features (across all heads).
    dim = num_heads * head_dim
    num_heads (int, optional): Number of attention heads. Defaults to 8.
    qkv_bias (bool, optional): If True, add a learnable bias to query, key, value. Defaults to False.
    qk_scale (float, optional): Override default qk scale of head_dim ** -0.5 if set. Defaults to None.
    attn_drop (float, optional): Dropout rate for attention weights. Defaults to 0.
    proj_drop (float, optional): Dropout rate for output projection. Defaults to 0.
"""
class Attention(nn.Module):
    def __init__(self, dim, num_heads=8, qkv_bias=False, qk_scale=None, attn_drop=0., proj_drop=0.):
        super().__init__()
        self.num_heads = num_heads
        head_dim = dim // num_heads
        self.scale = qk_scale or head_dim ** -0.5

        self.qkv = nn.Linear(dim, dim * 3, bias=qkv_bias)
        self.attn_drop = nn.Dropout(attn_drop)
        self.proj = nn.Linear(dim, dim)
        self.proj_drop = nn.Dropout(proj_drop)

    def forward(self, x):
        B, N, C = x.shape
        qkv = self.qkv(x).reshape(B, N, 3, self.num_heads, C // self.num_heads).permute(2, 0, 3, 1, 4)
        q, k, v = qkv[0], qkv[1], qkv[2]

        attn = (q @ k.transpose(-2, -1)) * self.scale
        attn = attn.softmax(dim=-1)
        attn = self.attn_drop(attn)

        x = (attn @ v).transpose(1, 2).reshape(B, N, C)
        x = self.proj(x)
        x = self.proj_drop(x)
        return x, attn



class Block(nn.Module):
    """Transformer block with multi-head attention and MLP. It applies layer normalization before the attention and MLP, and uses residual connections.
    parameters:
        dim (int): Number of input and output features (across all heads).
        (num_heads, qkv_bias, qk_scale, drop, attn_drop, drop_path, norm_layer): Attention's module parameters (see Attention for details).
        (drop, act_layer): MLP's module parameters (see MLP for details).
        mlp_ratio (float, optional): Ratio of hidden features to input features in MLP. Defaults to 4.
    """
    def __init__(self, dim, num_heads, mlp_ratio=4., qkv_bias=False, qk_scale=None, drop=0., attn_drop=0.,
                 drop_path=0., act_layer=nn.GELU, norm_layer=nn.LayerNorm):
        super().__init__()
        self.norm1 = norm_layer(dim)
        self.attn = Attention(
            dim, num_heads=num_heads, qkv_bias=qkv_bias, qk_scale=qk_scale, attn_drop=attn_drop, proj_drop=drop)
        self.drop_path = DropPath(drop_path) if drop_path > 0. else nn.Identity()
        self.norm2 = norm_layer(dim)
        mlp_hidden_dim = int(dim * mlp_ratio)
        self.mlp = MLP(in_features=dim, hidden_features=mlp_hidden_dim, act_layer=act_layer, drop=drop)

    def forward(self, x, return_attention=False):
        y, attn = self.attn(self.norm1(x))
        if return_attention:
            return attn
        x = x + self.drop_path(y)
        x = x + self.drop_path(self.mlp(self.norm2(x)))
        return x



class FlowFeatureEmbed(nn.Module):
    """Embedding layer for flow features, mapping categorical and continuous features to a sequence of tokens.
    parameters:
        cat_cardinalities (list[int]): List of the cardinalities (nb of unique values) for each categorical feature.
        num_continuous (int): Number of continuous features.
        embed_dim (int): Dimension of the embedding space.
    """

    def __init__(self, cat_cardinalities: list[int], num_continuous: int, embed_dim: int = 768):
        super().__init__()
        self.cat_cardinalities = list(cat_cardinalities)
        self.num_continuous = num_continuous
        self.num_tokens = len(self.cat_cardinalities) + self.num_continuous
        self.embed_dim = embed_dim

        #embedding layers for categorical features
        self.cat_embeds = nn.ModuleList([
            nn.Embedding(num_embeddings=card, embedding_dim=embed_dim)
            for card in self.cat_cardinalities
        ])
        #projection layers for continuous features
        self.cont_projs = nn.ModuleList([
            nn.Linear(in_features=1, out_features=embed_dim)
            for _ in range(self.num_continuous)
        ])
        #plays the role of positional/patch identity for each flow column
        self.col_identity = nn.Parameter(torch.zeros(1, self.num_tokens, embed_dim))
        nn.init.trunc_normal_(self.col_identity, std=0.02)

    def forward(self, x_cat: torch.Tensor, x_cont: torch.Tensor) -> torch.Tensor:
        # x_cat: (B, num_cat) int64/int32 | x_cont: (B, num_cont) float32
        tokens = [emb(x_cat[:, i]) for i, emb in enumerate(self.cat_embeds)] # = (B, num_cat, embed_dim)
        for j, proj in enumerate(self.cont_projs):
            val = x_cont[:, j : j + 1]  
            tokens.append(proj(val)) # append an new embedding of a continuous feature = (B, 1, embed_dim)

        x = torch.stack(tokens, dim=1)  # (B, num_tokens, embed_dim)
        #add column identity to each token to provide a unique representation for each feature
        return x + self.col_identity
    
    
    class NetFlowTPredictor(nn.Module):
        """ Network Flow Transformer-based Predictor module. It takes as input a sequence of tokens representing 
        the flow features (in the latent space), applies a series of transformer blocks, and outputs predictions for the masked tokens.
        parameters:
            num_patches (int): Number of tokens in the input sequence (number of flow features).
            embed_dim (int, optional): Dimension of the input token embeddings. Defaults to 768.
            predictor_embed_dim (int, optional): dimension of the bottleneck embedding in the predictor. Defaults to 384.
            depth (int, optional): Number of transformer blocks in the predictor. Defaults to 6.
            (num_heads, qkv_bias, qk_scale, drop, attn_drop, drop_path, norm_layer): Attention's module parameters (see Attention for details).
            (drop, act_layer): MLP's module parameters (see MLP for details).
            drop_rate (float, optional): Dropout rate for the input tokens. Defaults to 0.0.
            attn_drop_rate (float, optional): Dropout rate for the attention weights. Defaults to 0.0.
            drop_path_rate (float, optional): Stochastic depth decay rate for the transformer blocks. Defaults to 0.0.
            init_std (float, optional): Standard deviation for initializing the weights of the predictor layers. Defaults to 0.02.
        """
    def __init__(
        self, 
        num_tokens,
        embed_dim=768,
        predictor_embed_dim=384,
        depth=6,
        num_heads=12,
        mlp_ratio=4.0,
        qkv_bias=True,
        qk_scale=None,
        drop_rate=0.0,
        attn_drop_rate=0.0,
        drop_path_rate=0.0,
        norm_layer=nn.LayerNorm,
        init_std=0.02,
        **kwargs
    ):
        super().__init__()
        self.predictor_embed = nn.Linear(embed_dim, predictor_embed_dim, bias=True)
        dpr = [x.item() for x in torch.linspace(0, drop_path_rate, depth)]  # stochastic depth decay rule
        
        self.mask_token = nn.Parameter(torch.zeros(1, 1, predictor_embed_dim))    
        self.predictor_pos_embed = nn.Parameter(torch.zeros(1, num_tokens, predictor_embed_dim))
        
        self.predictor_blocks = nn.ModuleList([
            Block(
                dim=predictor_embed_dim, num_heads=num_heads, mlp_ratio=mlp_ratio, qkv_bias=qkv_bias, qk_scale=qk_scale,
                drop=drop_rate, attn_drop=attn_drop_rate, drop_path=dpr[i], norm_layer=norm_layer)
            for i in range(depth)])
        self.predictor_norm = norm_layer(predictor_embed_dim)
        self.predictor_proj = nn.Linear(predictor_embed_dim, embed_dim, bias=True)

        self.init_std = init_std
        trunc_normal_(self.mask_token, std=self.init_std)
        trunc_normal_(self.predictor_pos_embed, std=self.init_std)
        self.apply(self._init_weights)
        self.fix_init_weight()

    def fix_init_weight(self):
        def rescale(param, layer_id):
            param.div_(math.sqrt(2.0 * layer_id))

        for layer_id, layer in enumerate(self.predictor_blocks):
            rescale(layer.attn.proj.weight.data, layer_id + 1)
            rescale(layer.mlp.fc2.weight.data, layer_id + 1)

    def _init_weights(self, m):
        if isinstance(m, nn.Linear):
            trunc_normal_(m.weight, std=self.init_std)
            if isinstance(m, nn.Linear) and m.bias is not None:
                nn.init.constant_(m.bias, 0)
        elif isinstance(m, nn.LayerNorm):
            nn.init.constant_(m.bias, 0)
            nn.init.constant_(m.weight, 1.0)
        elif isinstance(m, nn.Embedding):
            # TODO: check if we are not overwriting missing conventional initialization for embedding layers
            trunc_normal_(m.weight, std=self.init_std)
            

    def forward(self, x, masks_x, masks):
        assert (masks is not None) and (masks_x is not None), 'Cannot run predictor without mask indices'

        if not isinstance(masks_x, list):
            masks_x = [masks_x]

        if not isinstance(masks, list):
            masks = [masks]

        # -- Batch Size
        B = len(x) // len(masks_x)

        # -- map from encoder-dim to pedictor-dim
        x = self.predictor_embed(x)

        # -- add positional embedding to x tokens
        x_pos_embed = self.predictor_pos_embed.repeat(B, 1, 1)
        x += apply_masks(x_pos_embed, masks_x)

        _, N_ctxt, D = x.shape

        # -- concat mask tokens to x
        pos_embs = self.predictor_pos_embed.repeat(B, 1, 1)
        pos_embs = apply_masks(pos_embs, masks)
        pos_embs = repeat_interleave_batch(pos_embs, B, repeat=len(masks_x))
        # --
        pred_tokens = self.mask_token.repeat(pos_embs.size(0), pos_embs.size(1), 1)
        # --
        pred_tokens += pos_embs
        x = x.repeat(len(masks), 1, 1)
        x = torch.cat([x, pred_tokens], dim=1)

        # -- fwd prop
        for blk in self.predictor_blocks:
            x = blk(x)
        x = self.predictor_norm(x)

        # -- return preds for mask tokens
        x = x[:, N_ctxt:]
        x = self.predictor_proj(x)

        return x
    
    
